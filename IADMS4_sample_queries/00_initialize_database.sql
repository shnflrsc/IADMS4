CREATE DATABASE IF NOT EXISTS iadms
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_0900_ai_ci;

USE iadms;

CREATE TABLE COMPANY (
    Company_ID    INT           NOT NULL AUTO_INCREMENT,
    Company_Name  VARCHAR(100)  NOT NULL,
    CONSTRAINT PK_COMPANY PRIMARY KEY (Company_ID),
    CONSTRAINT UQ_COMPANY_Name UNIQUE (Company_Name)
) ENGINE = InnoDB;

CREATE TABLE PERSON (
    Person_ID  INT                    NOT NULL AUTO_INCREMENT,
    Name       VARCHAR(100)           NOT NULL,
    Gender     ENUM('MALE', 'FEMALE') NOT NULL,
    Birthdate  DATE                   NOT NULL,
    CONSTRAINT PK_PERSON PRIMARY KEY (Person_ID)
) ENGINE = InnoDB;

CREATE TABLE STUDENT (
    Person_ID   INT          NOT NULL,
    Student_No  VARCHAR(20)  NOT NULL,
    Section     VARCHAR(30)  NOT NULL DEFAULT '',
    CONSTRAINT PK_STUDENT PRIMARY KEY (Person_ID),
    CONSTRAINT UQ_STUDENT_No UNIQUE (Student_No),
    CONSTRAINT FK_STUDENT_PERSON FOREIGN KEY (Person_ID)
        REFERENCES PERSON (Person_ID) ON DELETE CASCADE
) ENGINE = InnoDB;

CREATE TABLE COORDINATOR (
    Person_ID    INT          NOT NULL,
    Employee_ID  VARCHAR(20)  NOT NULL,
    CONSTRAINT PK_COORDINATOR PRIMARY KEY (Person_ID),
    CONSTRAINT FK_COORDINATOR_PERSON FOREIGN KEY (Person_ID)
        REFERENCES PERSON (Person_ID) ON DELETE CASCADE
) ENGINE = InnoDB;

CREATE TABLE `POSITION` (
    Position_ID     INT           NOT NULL AUTO_INCREMENT,
    Company_ID      INT           NOT NULL,
    Title           VARCHAR(100)  NOT NULL,
    Required_Hours  INT           NOT NULL,
    CONSTRAINT PK_POSITION PRIMARY KEY (Position_ID),
    CONSTRAINT CK_POSITION_Hours CHECK (Required_Hours > 0),
    CONSTRAINT FK_POSITION_COMPANY FOREIGN KEY (Company_ID)
        REFERENCES COMPANY (Company_ID)
) ENGINE = InnoDB;

CREATE TABLE COMPANY_REPRESENTATIVE (
    Person_ID   INT  NOT NULL,
    Company_ID  INT  NOT NULL,
    CONSTRAINT PK_COMPANY_REPRESENTATIVE PRIMARY KEY (Person_ID),
    CONSTRAINT FK_REP_PERSON FOREIGN KEY (Person_ID)
        REFERENCES PERSON (Person_ID) ON DELETE CASCADE,
    CONSTRAINT FK_REP_COMPANY FOREIGN KEY (Company_ID)
        REFERENCES COMPANY (Company_ID)
) ENGINE = InnoDB;

CREATE TABLE INTERN (
    Person_ID       INT  NOT NULL,
    Position_ID     INT  NOT NULL,
    Recorded_Hours  INT  NOT NULL DEFAULT 0,
    Intern_Status   ENUM('ACTIVE', 'DEACTIVATED', 'COMPLETED') NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT PK_INTERN PRIMARY KEY (Person_ID),
    CONSTRAINT CK_INTERN_Hours CHECK (Recorded_Hours >= 0),
    CONSTRAINT FK_INTERN_STUDENT FOREIGN KEY (Person_ID)
        REFERENCES STUDENT (Person_ID),
    CONSTRAINT FK_INTERN_POSITION FOREIGN KEY (Position_ID)
        REFERENCES `POSITION` (Position_ID)
) ENGINE = InnoDB;

CREATE TABLE ACCOUNT (
    Email      VARCHAR(100)  NOT NULL,
    Person_ID  INT           NOT NULL,
    Password   VARCHAR(50)   NOT NULL,
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (Email),
    CONSTRAINT UQ_ACCOUNT_Person UNIQUE (Person_ID),
    CONSTRAINT CK_ACCOUNT_Password CHECK (CHAR_LENGTH(Password) >= 4),
    CONSTRAINT FK_ACCOUNT_PERSON FOREIGN KEY (Person_ID)
        REFERENCES PERSON (Person_ID) ON DELETE CASCADE
) ENGINE = InnoDB;

CREATE TABLE OPENING (
    Opening_ID      INT  NOT NULL AUTO_INCREMENT,
    Position_ID     INT  NOT NULL,
    Opening_Status  ENUM('OPEN', 'CLOSED') NOT NULL DEFAULT 'OPEN',
    CONSTRAINT PK_OPENING PRIMARY KEY (Opening_ID),
    CONSTRAINT FK_OPENING_POSITION FOREIGN KEY (Position_ID)
        REFERENCES `POSITION` (Position_ID)
) ENGINE = InnoDB;

CREATE TABLE APPLICATION (
    Application_ID      INT  NOT NULL AUTO_INCREMENT,
    Student_ID          INT  NOT NULL,
    Opening_ID          INT  NOT NULL,
    Coordinator_ID      INT  NOT NULL,
    Application_Status  ENUM('PENDING', 'REJECTED', 'APPROVED', 'WITHDRAWN') NOT NULL DEFAULT 'PENDING',
    CONSTRAINT PK_APPLICATION PRIMARY KEY (Application_ID),
    CONSTRAINT FK_APPLICATION_STUDENT FOREIGN KEY (Student_ID)
        REFERENCES STUDENT (Person_ID),
    CONSTRAINT FK_APPLICATION_OPENING FOREIGN KEY (Opening_ID)
        REFERENCES OPENING (Opening_ID),
    CONSTRAINT FK_APPLICATION_COORDINATOR FOREIGN KEY (Coordinator_ID)
        REFERENCES COORDINATOR (Person_ID)
) ENGINE = InnoDB;

CREATE TABLE DAILY_LOG (
    Log_ID       INT           NOT NULL AUTO_INCREMENT,
    Intern_ID    INT           NOT NULL,
    Log_Date     DATE          NOT NULL,
    Hours        INT           NOT NULL,
    Description  VARCHAR(255)  NOT NULL,
    CONSTRAINT PK_DAILY_LOG PRIMARY KEY (Log_ID),
    CONSTRAINT CK_DAILY_LOG_Hours CHECK (Hours BETWEEN 1 AND 24),
    CONSTRAINT FK_DAILY_LOG_INTERN FOREIGN KEY (Intern_ID)
        REFERENCES INTERN (Person_ID)
) ENGINE = InnoDB;

CREATE TABLE EVALUATION (
    Evaluation_ID    INT           NOT NULL AUTO_INCREMENT,
    Intern_ID        INT           NOT NULL,
    Evaluator_ID     INT           NOT NULL,
    Rating           INT           NOT NULL,
    Comments         VARCHAR(500)  NOT NULL,
    Evaluation_Date  DATE          NOT NULL,
    CONSTRAINT PK_EVALUATION PRIMARY KEY (Evaluation_ID),
    CONSTRAINT UQ_EVALUATION_Intern UNIQUE (Intern_ID),
    CONSTRAINT CK_EVALUATION_Rating CHECK (Rating BETWEEN 1 AND 5),
    CONSTRAINT FK_EVALUATION_INTERN FOREIGN KEY (Intern_ID)
        REFERENCES INTERN (Person_ID),
    CONSTRAINT FK_EVALUATION_REP FOREIGN KEY (Evaluator_ID)
        REFERENCES COMPANY_REPRESENTATIVE (Person_ID)
) ENGINE = InnoDB;
