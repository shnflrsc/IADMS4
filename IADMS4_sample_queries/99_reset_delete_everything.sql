USE iadms;

SET FOREIGN_KEY_CHECKS = 0;

TRUNCATE TABLE EVALUATION;
TRUNCATE TABLE DAILY_LOG;
TRUNCATE TABLE APPLICATION;
TRUNCATE TABLE OPENING;
TRUNCATE TABLE ACCOUNT;
TRUNCATE TABLE INTERN;
TRUNCATE TABLE COMPANY_REPRESENTATIVE;
TRUNCATE TABLE `POSITION`;
TRUNCATE TABLE COORDINATOR;
TRUNCATE TABLE STUDENT;
TRUNCATE TABLE PERSON;
TRUNCATE TABLE COMPANY;

SET FOREIGN_KEY_CHECKS = 1;

SELECT 'EVALUATION' AS TableName, COUNT(*) AS Rows_Left FROM EVALUATION
UNION ALL SELECT 'DAILY_LOG', COUNT(*) FROM DAILY_LOG
UNION ALL SELECT 'APPLICATION', COUNT(*) FROM APPLICATION
UNION ALL SELECT 'OPENING', COUNT(*) FROM OPENING
UNION ALL SELECT 'ACCOUNT', COUNT(*) FROM ACCOUNT
UNION ALL SELECT 'INTERN', COUNT(*) FROM INTERN
UNION ALL SELECT 'COMPANY_REPRESENTATIVE', COUNT(*) FROM COMPANY_REPRESENTATIVE
UNION ALL SELECT 'POSITION', COUNT(*) FROM `POSITION`
UNION ALL SELECT 'COORDINATOR', COUNT(*) FROM COORDINATOR
UNION ALL SELECT 'STUDENT', COUNT(*) FROM STUDENT
UNION ALL SELECT 'PERSON', COUNT(*) FROM PERSON
UNION ALL SELECT 'COMPANY', COUNT(*) FROM COMPANY;
